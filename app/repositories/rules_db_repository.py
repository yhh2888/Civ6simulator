"""Read access to the XML-derived rules database (app/data/rules_db.json).

The database is generated by ``tools/build_rules_db.py``. It is read-only at
runtime and cached by file path and modification time. When the file is
missing, an empty database is returned and every data-driven rule reports
itself as unavailable instead of guessing values.
"""

from __future__ import annotations

import json
import threading
from pathlib import Path
from typing import Any

from app.repositories import locations

_LOCK = threading.RLock()
_CACHE: dict[str, Any] = {"by_path": {}, "override": None}


def rules_db_file() -> Path:
    return locations.rules_db_file()


class RulesDB:
    """Indexed view over merged XML tables."""

    def __init__(self, payload: dict[str, Any] | None):
        payload = payload if isinstance(payload, dict) else {}
        self.available = bool(payload.get("tables"))
        self.meta = {
            key: payload.get(key)
            for key in ("format", "format_version", "generated_at", "source", "fingerprint", "stats", "ruleset")
        }
        self.tables: dict[str, list[dict]] = {
            name: [row for row in rows if isinstance(row, dict)]
            for name, rows in (payload.get("tables") or {}).items()
            if isinstance(rows, list)
        }
        self.global_parameters: dict[str, str] = dict(
            payload.get("global_parameters") or {}
        )
        self._index_cache: dict[tuple[str, str], dict[str, dict]] = {}
        self._group_cache: dict[tuple[str, str], dict[str, list[dict]]] = {}

    def rows(self, table: str) -> list[dict]:
        return self.tables.get(table, [])

    def index(self, table: str, key: str) -> dict[str, dict]:
        cache_key = (table, key)
        if cache_key not in self._index_cache:
            self._index_cache[cache_key] = {
                row[key]: row for row in self.rows(table) if isinstance(row.get(key), str)
            }
        return self._index_cache[cache_key]

    def group(self, table: str, key: str) -> dict[str, list[dict]]:
        cache_key = (table, key)
        if cache_key not in self._group_cache:
            grouped: dict[str, list[dict]] = {}
            for row in self.rows(table):
                value = row.get(key)
                if isinstance(value, str):
                    grouped.setdefault(value, []).append(row)
            self._group_cache[cache_key] = grouped
        return self._group_cache[cache_key]

    def param(self, name: str, default: float | None = None) -> float | None:
        value = self.global_parameters.get(name)
        if value is None:
            return default
        try:
            return float(value)
        except (TypeError, ValueError):
            return default

    def has_param(self, name: str) -> bool:
        return name in self.global_parameters


def load_rules_db(ruleset: str | None = None) -> RulesDB:
    """Rules for ``ruleset`` (e.g. RULESET_EXPANSION_2); base rules otherwise.

    Falls back to the base database when no file exists for the ruleset.
    """
    path = locations.rules_db_file_for(ruleset) if ruleset else rules_db_file()
    try:
        stat = path.stat()
        key = (str(path), stat.st_mtime_ns, stat.st_size)
    except OSError:
        key = (str(path), None, None)
    with _LOCK:
        if _CACHE["override"] is not None:
            return _CACHE["override"]
        cached = _CACHE["by_path"].get(str(path))
        if cached is not None and cached[0] == key:
            return cached[1]
        payload = None
        if key[1] is not None:
            try:
                payload = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                payload = None
        db = RulesDB(payload)
        _CACHE["by_path"][str(path)] = (key, db)
        return db


def available_rulesets() -> dict[str, bool]:
    return {name: locations.rules_db_file_for(name) != rules_db_file() for name in locations.RULESET_FILES}


def set_rules_db_for_tests(payload: dict[str, Any] | None) -> RulesDB:
    """Install an in-memory database (used by tests)."""
    db = RulesDB(payload)
    with _LOCK:
        _CACHE.update(override=db)
    return db


def clear_rules_db_cache() -> None:
    with _LOCK:
        _CACHE.update(by_path={}, override=None)
